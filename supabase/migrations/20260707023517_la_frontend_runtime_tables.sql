create or replace view public.la_school_engagement_monthly
with (security_invoker = true) as
select
  date_trunc('month', r.created_at)::date as month,
  r.school_id,
  count(distinct r.id)::integer as review_count,
  count(distinct c.id)::integer as comment_count,
  count(distinct rr.id)::integer as reaction_count,
  count(distinct p.id)::integer as photo_count,
  (
    count(distinct r.id) * 10
    + count(distinct c.id) * 3
    + count(distinct rr.id)
    + count(distinct p.id) * 5
  )::numeric as score
from public.la_reviews r
left join public.la_review_comments c on c.rating_id = r.id
left join public.la_review_reactions rr on rr.rating_id = r.id
left join public.la_review_photos p on p.review_id = r.id and p.deleted_at is null
group by 1, r.school_id;

create or replace view public.la_school_menu_stats_monthly
with (security_invoker = true) as
select
  date_trunc('month', r.created_at)::date as month,
  r.school_id,
  r.selected_menu_item as menu_item,
  count(*)::integer as pick_count,
  avg(r.score)::numeric as avg_score,
  count(p.id)::integer as photo_count
from public.la_reviews r
left join public.la_review_photos p on p.review_id = r.id and p.deleted_at is null
where r.selected_menu_item is not null and btrim(r.selected_menu_item) <> ''
group by 1, r.school_id, r.selected_menu_item;

create or replace function public.la_find_battle_opponents(
  p_my_lat double precision,
  p_my_lng double precision,
  p_my_type text,
  p_my_id bigint,
  p_date date,
  p_limit integer default 20
)
returns table (
  school_id bigint,
  school_name text,
  school_type text,
  address text,
  atpt_code text,
  school_code text,
  meal_id bigint,
  auto_score integer,
  auto_rank text,
  menu jsonb,
  distance_km double precision
)
language sql
stable
as $$
  select
    s.id,
    s.name,
    s.type,
    s.address,
    s.atpt_code,
    s.school_code,
    m.id,
    m.auto_score,
    m.auto_rank,
    m.menu,
    (
      6371 * acos(
        least(1, greatest(-1,
          cos(radians(p_my_lat)) * cos(radians(s.lat::double precision))
          * cos(radians(s.lng::double precision) - radians(p_my_lng))
          + sin(radians(p_my_lat)) * sin(radians(s.lat::double precision))
        ))
      )
    )::double precision as distance_km
  from public.la_schools s
  join public.la_meals m on m.school_id = s.id and m.meal_date = p_date
  where s.id <> p_my_id
    and s.lat is not null
    and s.lng is not null
    and (p_my_type is null or p_my_type = '' or s.type ilike '%' || p_my_type || '%')
  order by distance_km asc, m.auto_score desc nulls last
  limit least(greatest(coalesce(p_limit, 20), 1), 100);
$$;

