insert into public.la_schools (id, name, type, address, atpt_code, school_code, lat, lng, created_at)
select id, name, type, address, atpt_code, school_code, lat, lng, coalesce(created_at, now())
from public.schools
on conflict (id) do update
set name = excluded.name,
    type = excluded.type,
    address = excluded.address,
    atpt_code = excluded.atpt_code,
    school_code = excluded.school_code,
    lat = excluded.lat,
    lng = excluded.lng;

